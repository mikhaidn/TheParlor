// Generates site/parlor/tokens.css from design/tokens.json.
// Run: node tools/build-tokens.mjs (also run by tools/build.mjs)
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const t = JSON.parse(readFileSync(join(root, 'design/tokens.json'), 'utf8'));

const light = [], dark = [];
const put = (name, value) => {
  if (value && typeof value === 'object') {
    light.push(`  --${name}: ${value.light};`);
    if (value.dark && value.dark !== value.light) dark.push(`  --${name}: ${value.dark};`);
  } else light.push(`  --${name}: ${value};`);
};

for (const tok of t.color.tokens) put(tok.name, tok.value);
for (const [k, v] of Object.entries(t.type.families)) put(`font-${k}`, v);
for (const group of ['spacing', 'radius', 'card', 'shadow', 'layout']) {
  for (const tok of (t[group]?.tokens || [])) put(tok.name, tok.value);
}

const css = `/* Generated by tools/build-tokens.mjs from design/tokens.json — do not edit by hand. */
:root, [data-theme="light"] {
${light.join('\n')}
  color-scheme: light;
}
[data-theme="dark"] {
${dark.join('\n')}
  color-scheme: dark;
}
`;
writeFileSync(join(root, 'site/parlor/tokens.css'), css);
console.log(`tokens.css: ${light.length} tokens, ${dark.length} dark overrides`);
